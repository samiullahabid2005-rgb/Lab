export function getTestById(id: string): LabTest | undefined {
  return tests.find((t) => t.id === id);
}

export function getPopularTests(): LabTest[] {
  return tests.filter((t) => t.popular);
}

export function getRelatedTests(test: LabTest, limit = 4): LabTest[] {
  return tests.filter((t) => t.id !== test.id && t.category === test.category).slice(0, limit);
}

export function searchTests(query: string): LabTest[] {
  const q = query.trim().toLowerCase();
  if (!q) return tests;
  return tests.filter(
    (t) =>
      t.name.toLowerCase().includes(q) ||
      t.abbreviation.toLowerCase().includes(q) ||
      t.category.toLowerCase().includes(q) ||
      (t.panel ? t.panel.toLowerCase().includes(q) : false)
  );
}
